import streamlit as st

# Сайттың баптаулары
st.set_page_config(page_title="Болашақ соты", page_icon="⚖️", layout="centered")

# Басты тақырып
st.title("⚖️ Болашақ соты: Экологиялық симулятор")
st.markdown("**«OBAL PRO» жобасы аясында 9-сынып оқушыларына арналған интерактивті тренажер**")
st.divider()

# 1-ҚАДАМ
st.header("1-қадам. Экологиялық жағдаятты (Кейсті) таңдау 🌍")
case = st.radio("Төмендегі жағдаяттардың бірін таңдаңыз:", [
    "🏭 Ауыл маңындағы өзен жағасынан алтын қазатын фабрика ашу",
    "🏢 Қала ішіндегі саябақты (ағаштарды) кесіп, үлкен Ойын-сауық орталығын салу",
    "🛢️ Ескі зауыттың химиялық қалдықтарын далаға көме салу",
    "✍️ Өз жағдаятымды жазамын (өз нұсқам)"
])

custom_case = ""
if case == "✍️ Өз жағдаятымды жазамын (өз нұсқам)":
    custom_case = st.text_input("Өз жағдаятыңызды осында қысқаша жазыңыз:")

selected_case = custom_case if case == "✍️ Өз жағдаятымды жазамын (өз нұсқам)" else case

st.divider()

# 2-ҚАДАМ
st.header("2-қадам. Тақырыптық терминдер және «ОБАЛ» ұғымы 🔍")
st.write("Бұл жағдайда қандай экологиялық қағида бұзылып тұр? (Бірнешеуін таңдауға болады)")

terms = st.multiselect("Экологиялық терминдер:", [
    "Биоалуантүрліліктің жойылуы (жануарлар мен өсімдіктердің құруы)",
    "Топырақ эрозиясы / деградация (жердің құрғауы)",
    "Су ресурстарының ластануы және сарқылуы",
    "Парниктік газдардың көбеюі (ауаның ластануы)"
])

obal = st.multiselect("Ұлттық экологиялық дәстүр («Обал» концепциясы):", [
    "💧 «Судың да сұрауы бар» (Суды ысырап ету)",
    "🌱 «Көкті жұлма, көктей соларсың» (Табиғатқа, флораға зиян келтіру)",
    "🦌 «Киелі аңға оқ атпа» (Фаунаны құрту, тіршілік иесіне қиянат жасау)"
])

st.divider()

# 3-ҚАДАМ
st.header("3-қадам. Құқықтық-нормативтік құжаттар 📜")
laws = st.multiselect("Сот шешімін шығару үшін қай заңға сүйенеміз?", [
    "🏛 ҚР Конституциясы (37-бап): Азаматтар табиғатты сақтауға және ұқыпты қарауға міндетті.",
    "📗 Экологиялық кодекс: Қазіргі және болашақ ұрпақтың қажеттіліктерін тең ескеру, «Ластаушы төлейді» қағидаты.",
    "🌍 Халықаралық заң (Париж келісімі): Климаттың өзгеруіне және экологиялық апаттарға жол бермеу."
])

st.divider()

# 4-ҚАДАМ
st.header("4-қадам. Болашаққа баға (Таразы) ⚖️")
st.write("25 жылдан кейінгі пайда мен зиянды салыстырыңыз (1-2 сөйлеммен):")

benefit = st.text_input("💰 Бүгінгі ПАЙДА қандай? (Мысалы: адамдарға жұмыс табылады, үкіметке салық түседі)")
harm = st.text_input("⚠️ Ертеңгі (25 жылдан кейінгі) ЗИЯН қандай? (Мысалы: ауылдың суы ішуге жарамсыз болады, ауру көбейеді)")

st.divider()

# 5-ҚАДАМ
st.header("5-қадам. БОЛАШАҚ СОТЫНЫҢ ҮКІМІ 👨‍⚖️")
verdict = st.radio("Қорытынды шешіміңізді қабылдаңыз:", [
    "🔴 ЖОБА ТОҚТАТЫЛСЫН! (Табиғатқа келетін қайтымсыз зиян өте жоғары, болашаққа обал)",
    "🟡 ШАРТПЕН РҰҚСАТ БЕРІЛСІН! (Зауыт қымбат фильтр орнатып, зиянның орнын толтырған жағдайда ғана)",
    "🟢 ЖОБАҒА РҰҚСАТ! (Экологияға еш зияны жоқ, болашақ ұрпаққа қауіпсіз)"
])

st.divider()

# ҚОРЫТЫНДЫ ШЫҒАРУ БАТЫРМАСЫ
if st.button("⚖️ СОТ ҮКІМІН ЖАРИЯЛАУ"):
    st.success("✅ Сіздің экологиялық талдауыңыз сәтті аяқталды!")
    
    st.markdown("### 📋 ТАЛДАУ ҚОРЫТЫНДЫСЫ:")
    st.write(f"**Қаралған іс (Кейс):** {selected_case}")
    
    if terms or obal:
        st.write("**Бұзылған экологиялық талаптар мен дәстүрлер:**")
        for t in terms:
            st.write(f"- {t}")
        for o in obal:
            st.write(f"- {o}")
            
    if laws:
        st.write("**Қолданылған құқықтық құжаттар:**")
        for l in laws:
            st.write(f"- {l}")
            
    st.write(f"**Бүгінгі пайда:** {benefit}")
    st.write(f"**Болашақтағы зиян:** {harm}")
    
    st.markdown(f"### 🎯 СОТ ШЕШІМІ:\n **{verdict}**")
    
    st.info("💡 OBAL PRO: Болашақ ұрпақтың табиғатын бүгін қорғаймыз!")
