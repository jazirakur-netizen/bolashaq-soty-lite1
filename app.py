def recommendation(index: float):
    if index < 30:
        return "Рұқсат беру", "Төмен қауіп", "#138a5b"
    if index < 60:
        return "Қатаң шарттармен рұқсат беру", "Орташа қауіп", "#c48a00"
    if index < 80:
        return "Жобаны тоқтатып, қайта қарау", "Жоғары қауіп", "#d75b32"
    return "Рұқсат бермеу", "Өте жоғары қауіп", "#a62335"


